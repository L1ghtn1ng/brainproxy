#!/usr/bin/env python3
"""Generate the feed's PHP known-vulnerability checks from ZAP's data.

Covers ZAP's ServerSideVersionScanRule (pscanrules, alert 20020, Apache License 2.0)
as signed feed checks instead of a compiled-in port, so new PHP advisories reach
installs without a release. The data is ZAP's php-known-vulnerabilities.json at the
commit pinned in zap-sync.json (or --from FILE).

One passive check per severity band, so a response gets at most one finding per band
rather than one per CVE; each CVE is a named DSL matcher, listed in the finding's
"Matched:" line. CVEs that brainproxy's own rule 100001 (PHP2Shell) already reports
are left out. Unlike ZAP, versions without a patch number (PHP/8.2) aren't matched:
ZAP reports those at low confidence, and they match nearly every advisory.

After running it, sign the feed: brainproxy checks feed sign feed --key <key>
"""
import argparse
import json
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
SYNC = ROOT / "zap-sync.json"
OUT = ROOT / "feed" / "passive" / "php"
DATA = "addOns/pscanrules/src/main/resources/org/zaproxy/zap/extension/pscanrules/resources/php-known-vulnerabilities.json"
# Reported by the built-in PHP2Shell rule (100001) with more specific advice.
COVERED = {"CVE-2026-109618", "CVE-2026-109619"}
BANDS = ["critical", "high", "medium", "low"]
VERSION = re.compile(r"^\d+(\.\d+)*$")


def load(args):
    if args.source:
        return json.loads(pathlib.Path(args.source).read_text())
    sync = json.loads(SYNC.read_text())
    repo = sync["repository"].removeprefix("https://github.com/").removesuffix(".git")
    url = f"https://raw.githubusercontent.com/{repo}/{sync['commit']}/{DATA}"
    return json.loads(subprocess.run(["curl", "-fsSL", "--max-time", "30", url], check=True, capture_output=True).stdout)


def constraint(rng):
    for v in (rng["introduced"], rng.get("fixed")):
        if v is not None and not VERSION.match(v):
            raise SystemExit(f"unexpected version {v!r} in {rng}")
    parts = [] if rng["introduced"] == "0" else [f">= {rng['introduced']}"]
    if rng.get("fixed"):
        parts.append(f"< {rng['fixed']}")
    if not parts:
        raise SystemExit(f"range matches every version: {rng}")
    return ", ".join(parts)


def dsl(ranges):
    return " || ".join(f"compare_versions(php, '{constraint(r)}')" for r in ranges)


def label(v):
    # Matcher names are joined with ", " in the finding, so keep commas out.
    return f"{v['cve']} {v['name']}".replace(",", ";").strip()


def matchers(vulns):
    out = []
    for v in sorted(vulns, key=lambda v: (-v.get("cvss", 0), v["cve"])):
        known = [r for r in v["affected"] if not r.get("assumed")]
        assumed = [r for r in v["affected"] if r.get("assumed")]
        if known:
            out.append((label(v), dsl(known)))
        if assumed:
            # Older branches the advisory doesn't list, so presumed affected (as ZAP does).
            out.append((f"{label(v)} (assumed: branch not covered by the advisory)", dsl(assumed)))
    return out


def q(s):
    return json.dumps(s, ensure_ascii=False)


def render(band, vulns, updated):
    cves = ", ".join(sorted(v["cve"] for v in vulns))
    lines = [
        f"# Generated by scripts/php_feed.py from ZAP's php-known-vulnerabilities.json ({updated}).",
        "# Covers ZAP ServerSideVersionScanRule (pscanrules, Apache License 2.0). Don't edit by hand.",
        f"id: bp-php-known-vulnerabilities-{band}",
        "info:",
        f"  name: {q(f'PHP version with known {band} severity vulnerabilities')}",
        f"  severity: {band}",
        "  confidence: medium",
        "  description: |",
        "    The server disclosed its PHP version in a response header, and that version is",
        f"    affected by known {band} severity vulnerabilities in PHP itself. The matched",
        "    vulnerabilities are listed in the other info; versions are compared against PHP's",
        "    published security advisories. Some distributions backport security fixes without",
        "    changing the version number, so check whether the fixes have been applied before",
        "    reporting these as confirmed.",
        f"    Covered: {cves}.",
        "  remediation: |",
        "    Upgrade PHP to a supported version that includes the fixes for the listed",
        "    vulnerabilities. Also stop the server disclosing the PHP version: set",
        "    expose_php = Off in php.ini and remove version details from the Server header.",
        "  reference:",
        "    - https://www.php.net/supported-versions.php",
        "    - https://github.com/php/php-src/security/advisories",
        "  classification:",
        "    cwe-id: CWE-1395",
        f"  tags: php,cve,version,passive,{band}",
        "scope: passive",
        "http:",
        "  - extractors:",
        "      - type: regex",
        "        name: php",
        "        part: header",
        "        group: 1",
        "        regex:",
        "          - '(?im)(?:^|[^\\w-])PHP/(\\d{1,6}\\.\\d{1,6}\\.\\d{1,6})'",
        "    matchers-condition: or",
        "    matchers:",
    ]
    for name, expr in matchers(vulns):
        lines += ["      - type: dsl", f"        name: {q(name)}", "        dsl:", f"          - {q(expr)}"]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--from", dest="source", help="a local php-known-vulnerabilities.json")
    args = ap.parse_args()
    data = load(args)
    vulns = [v for v in data["vulnerabilities"] if v["cve"] not in COVERED]
    unknown = {v["severity"] for v in vulns} - set(BANDS)
    if unknown:
        raise SystemExit(f"unknown severities {unknown}")
    OUT.mkdir(parents=True, exist_ok=True)
    wanted = set()
    for band in BANDS:
        group = [v for v in vulns if v["severity"] == band]
        if not group:
            continue
        path = OUT / f"php-known-vulnerabilities-{band}.yaml"
        path.write_text(render(band, group, data.get("lastUpdated", "")))
        wanted.add(path.name)
        print(f"{path.relative_to(ROOT)}: {len(group)} CVEs")
    for stale in OUT.glob("*.yaml"):
        if stale.name not in wanted:
            stale.unlink()
            print(f"removed {stale.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
